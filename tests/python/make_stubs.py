"""
Generate the type stubs of the extension modules from the bindings

The stubs (python/packages/pycuampcor/_cpu.pyi and _cuda.pyi) declare the types of the
parameters (from their default values) and of the methods, with the docstrings of the
bindings. Run this script, with pycuampcor built with CUDA, when the bindings change:

    python tests/python/make_stubs.py

test_stubs.py checks that the stubs are up to date.
"""

import os
import re
import sys

import pycuampcor
from pycuampcor.options import _Option

STUB_DIR = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..",
                                         "python", "packages", "pycuampcor"))

HEADER = '''\
# Generated by tests/python/make_stubs.py from the bindings; do not edit.
import os
from typing import List, Sequence, SupportsIndex, Tuple, TypedDict, Union, overload

from .options import Algorithm, DataType, DerampAxis, DerampMethod, OversamplingMethod, Workflow

has_gdal: bool
has_hdf5: bool
'''

DEVICE_INFO = '''
class DeviceInfo(TypedDict):
    """A CUDA device (PyCuAmpcor.device_list)"""
    id: int
    name: str
    sm_count: int
    compute_capability: Tuple[int, int]
    total_memory: int
'''

# method -> (decorator, signature with {cls} for the class name)
METHODS = {
    "runAmpcor": ("", "(self) -> None"),
    "runAmpcorLayers": ("@staticmethod", "(layers: Sequence[{cls}]) -> None"),
    "isDoublePrecision": ("", "(self) -> bool"),
    "checkPixelInImageRange": ("", "(self) -> None"),
    "setupParams": ("", "(self) -> None"),
    "setConstantGrossOffset": ("", "(self, grossOffsetDown: SupportsIndex, "
                                   "grossOffsetAcross: SupportsIndex) -> None"),
    "setVaryingGrossOffset": ("", "(self, grossOffsetDown: Sequence[SupportsIndex], "
                                  "grossOffsetAcross: Sequence[SupportsIndex]) -> None"),
}
CUDA_METHODS = {
    "device_init": ("@staticmethod", "(device: SupportsIndex = 0) -> int"),
    "get_sm_count": ("@staticmethod", "(device: SupportsIndex = 0) -> int"),
    "device_list": ("@staticmethod", "() -> List[DeviceInfo]"),
}

GROSS_OFFSET = "Union[SupportsIndex, Sequence[SupportsIndex]]"


def param_types(value):
    """The (getter, setter) types of a parameter, from its default value"""
    if isinstance(value, _Option):
        name = type(value).__name__
        return name, f"Union[{name}, SupportsIndex, str]"
    if isinstance(value, bool):
        return "bool", "Union[bool, SupportsIndex]"
    if isinstance(value, str):
        return "str", "Union[str, os.PathLike[str]]"
    if isinstance(value, int):
        return "int", "SupportsIndex"
    raise TypeError(f"unexpected parameter type {type(value)}")


def docstring(doc, indent):
    """A docstring, indented"""
    doc = doc.strip()
    assert '"""' not in doc and "\\" not in doc
    lines = doc.split("\n")
    if len(lines) == 1:
        return f'{indent}"""{doc}"""\n'
    body = "\n".join((indent + line) if line else "" for line in lines[1:])
    return f'{indent}"""{lines[0]}\n{body}\n{indent}"""\n'


def function_doc(func):
    """The docstring of a bound function, without its signature"""
    return func.__doc__.split("\n\n", 1)[1]


def init_docs(cls):
    """The docstrings of the (two) overloaded constructors"""
    sections = re.split(r"^\d+\. __init__\(.*\n\n", cls.__init__.__doc__, flags=re.M)
    return [s.strip() for s in sections[1:]]


def class_stub(cls):
    """The stub of an ampcor class"""
    name = cls.__name__
    defaults = cls()
    params = [n for n, v in vars(cls).items() if isinstance(v, property) and v.fset]
    readonly = [n for n, v in vars(cls).items() if isinstance(v, property) and not v.fset]
    types = {n: param_types(getattr(defaults, n)) for n in params + readonly}

    out = f"\nclass {name}:\n" + docstring(cls.__doc__, "    ")
    doc_default, doc_kwargs = init_docs(cls)
    out += f"    @overload\n    def __init__(self) -> None:\n" + docstring(doc_default, "        ")
    kwargs = "".join(f"        {n}: {types[n][1]} = ...,\n" for n in params)
    kwargs += (f"        grossOffsetDown: {GROSS_OFFSET} = ...,\n"
               f"        grossOffsetAcross: {GROSS_OFFSET} = ...,\n")
    out += (f"    @overload\n    def __init__(\n        self,\n        *,\n{kwargs}"
            f"    ) -> None:\n" + docstring(doc_kwargs, "        "))

    for n in params:
        getter, setter = types[n]
        out += (f"    @property\n    def {n}(self) -> {getter}:\n"
                + docstring(getattr(cls, n).__doc__, "        ")
                + f"    @{n}.setter\n    def {n}(self, value: {setter}) -> None: ...\n")
    for n in readonly:
        out += (f"    @property\n    def {n}(self) -> {types[n][0]}:\n"
                + docstring(getattr(cls, n).__doc__, "        "))

    methods = dict(METHODS, **(CUDA_METHODS if hasattr(cls, "device_list") else {}))
    for n, (decorator, signature) in methods.items():
        if decorator:
            out += f"    {decorator}\n"
        out += (f"    def {n}{signature.format(cls=name)}:\n"
                + docstring(function_doc(getattr(cls, n)), "        "))
    return out


def module_stub(cls):
    """The stub of the extension module of the class cls (with the device info for CUDA)"""
    cuda = hasattr(cls, "device_list")
    return HEADER + (DEVICE_INFO if cuda else "") + class_stub(cls)


def stubs():
    """The stubs: file name -> content"""
    if not pycuampcor.has_cuda:
        sys.exit("pycuampcor must be built with CUDA to generate the stubs of both modules")
    return {"_cpu.pyi": module_stub(pycuampcor.PyCPUAmpcor),
            "_cuda.pyi": module_stub(pycuampcor.PyCuAmpcor)}


def main():
    """Write the stubs of the extension modules"""
    for name, content in stubs().items():
        path = os.path.join(STUB_DIR, name)
        with open(path, "w") as f:
            f.write(content)
        print("wrote", path)


if __name__ == "__main__":
    main()
